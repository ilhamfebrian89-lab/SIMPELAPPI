const parsedIsolationCategories = [];
let currentIsolationCategory = null;

isolationCategorySource
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter(Boolean)
  .forEach((line) => {
    if (/^Item Penilaian\s*:/i.test(line)) return;

    const assessmentMatch = line.match(/^\d+\s+(.+)$/);
    if (assessmentMatch) {
      if (!currentIsolationCategory) {
        throw new Error('Item penilaian ditemukan sebelum jenis kewaspadaan isolasi.');
      }
      currentIsolationCategory.items.push(assessmentMatch[1].trim());
      return;
    }

    const categoryNumber = parsedIsolationCategories.length + 1;
    const slug = line
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');

    currentIsolationCategory = {
      id: `${categoryNumber}-${slug}`,
      name: `${categoryNumber}. ${line}`,
      description: `Checklist penilaian ${line}.`,
      items: []
    };
    parsedIsolationCategories.push(currentIsolationCategory);
  });

const isolationAssessmentItemCount = parsedIsolationCategories.reduce(
  (total, category) => total + category.items.length,
  0
);

if (parsedIsolationCategories.length !== 29 || isolationAssessmentItemCount !== 284) {
  throw new Error(
    `Konfigurasi kewaspadaan isolasi tidak lengkap: ${parsedIsolationCategories.length} jenis dan ${isolationAssessmentItemCount} item.`
  );
}

window.simpelappiIsolationCategories = parsedIsolationCategories;
